/**
 * Code themes: a block's colors, and a style for each kind of token, written as inline CSS (an email has no
 * stylesheet a class could point to). Token kinds are highlight.js's scopes (`keyword`, `string`,
 * `title.function`, …); a scope a theme doesn't name takes its parent's style (`title.function` → `title`), or none.
 */
export interface CodeTheme {
  /** The block's background. */
  background: string;
  /** Text that isn't a token. */
  color: string;
  /** A border around the block (`1px solid #e2e5ea`), or none. */
  border?: string;
  /** Line numbers. */
  lineNumbers: string;
  /** Inline code (CodeInline): its background and text color. */
  inline: { background: string; color: string };
  /** CSS declarations by token scope: `{ keyword: "color: #b0326f", comment: "color: #6b7280; font-style: italic" }`. */
  tokens: Record<string, string>;
}

